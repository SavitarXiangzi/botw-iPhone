#!/usr/bin/env python3
"""Generate the NVN host-HLE ABI from ios/nvn/registry.json.

Outputs (all committed, all reproducible):
    ios/nvn/include/nvn_api.h        X-macro proc list + enum + prototypes
    ios/nvn/src/nvn_dispatch.cpp     name -> index (binary search) + backend hook
    docs/NVN_COVERAGE.md             per-domain scoreboard

The ABI is deliberately signature-agnostic.  NVN's real prototypes differ
between revisions (struct-by-value packing, handle types), and the Windows
prototype already treats every entry point as "read the raw argument
registers".  Keeping that contract means the prototype's Python HLE and the
iOS C++ HLE stay semantically identical, which is the whole point of doing the
port in this order.

`--check` re-generates in memory and fails if a committed artifact is stale,
so CI catches "someone edited the generated file by hand" and "someone forgot
to regenerate after touching the registry".

Usage:
    python gen_nvn.py --repo .            # write
    python gen_nvn.py --repo . --check    # verify
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HDR_BEGIN = "/* @generated by scripts/gen_nvn.py -- do not edit by hand. */"

DOC_BEGIN = "<!-- @generated by scripts/gen_nvn.py -- do not edit by hand. -->"


def load(repo: str) -> dict:
    with open(os.path.join(repo, "ios", "nvn", "registry.json"), encoding="utf-8") as fh:
        return json.load(fh)


def load_implemented(repo: str) -> list[str]:
    path = os.path.join(repo, "ios", "nvn", "implemented_metal.txt")
    if not os.path.exists(path):
        return []
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if line:
                out.append(line)
    return out


def gen_header(procs: list[dict]) -> str:
    names = [p["name"] for p in procs]
    lines = [
        HDR_BEGIN,
        "#ifndef NVN_API_H",
        "#define NVN_API_H",
        "",
        "#include <stdint.h>",
        "#include <string.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/* Opaque host-side context. One per emulated title process. */",
        "typedef struct nvngfx_ctx nvngfx_ctx;",
        "",
        "/*",
        " * The guest argument block, captured at the guest->host call site.",
        " *",
        " * `x` is x0..x7: integer/pointer arguments and integer/pointer returns.",
        " * `f` is s0..s7 / d0..d7: a float arrives in sN and is stored as 32",
        " * bits in the low half of f[N]; a double arrives in dN and fills all",
        " * 64 bits.  The second half is not optional:",
        " * nvnSamplerBuilderSetLodBias and friends pass values in FP registers,",
        " * not in x[].  The helpers below are the",
        " * only sanctioned way to move values in and out of f[].",
        " */",
        "typedef struct nvngfx_args {",
        "    uint64_t x[8];",
        "    uint64_t f[8];",
        "} nvngfx_args;",
        "",
        "static inline float nvngfx_arg_f32(const nvngfx_args* a, unsigned i) {",
        "    uint32_t bits = (uint32_t)a->f[i];",
        "    float v;",
        "    memcpy(&v, &bits, sizeof v);",
        "    return v;",
        "}",
        "static inline void nvngfx_arg_set_f32(nvngfx_args* a, unsigned i, float v) {",
        "    uint32_t bits;",
        "    memcpy(&bits, &v, sizeof v);",
        "    a->f[i] = bits;",
        "}",
        "static inline double nvngfx_arg_f64(const nvngfx_args* a, unsigned i) {",
        "    double v;",
        "    memcpy(&v, &a->f[i], sizeof v);",
        "    return v;",
        "}",
        "static inline void nvngfx_arg_set_f64(nvngfx_args* a, unsigned i, double v) {",
        "    memcpy(&a->f[i], &v, sizeof v);",
        "}",
        "",
        "/* One NVN entry point.  Handles and pointers are passed straight",
        " * through: guest memory is host-visible (unified memory), so there is",
        " * no marshalling layer. */",
        "typedef void (*nvngfx_proc)(nvngfx_ctx* ctx, nvngfx_args* args);",
        "",
        f"/* {len(names)} entry points, sorted by name. */",
        "#define NVN_PROC_LIST(X) \\",
    ]
    for n in names:
        lines.append(f"    X({n}) \\")
    lines[-1] = lines[-1].rstrip(" \\")
    lines += [
        "",
        "typedef enum {",
        "#define NVN_ENUM_ENTRY(n) NVN_IDX_##n,",
        "    NVN_PROC_LIST(NVN_ENUM_ENTRY)",
        "#undef NVN_ENUM_ENTRY",
        "    NVN_PROC_COUNT",
        "} nvn_proc_index;",
        "",
        "/* Stable name for logging; never NULL for a valid index. */",
        "const char* nvngfx_proc_name(nvn_proc_index idx);",
        "",
        "/* Guest entry point installed for `name`, or NULL if the title never asks",
        " * for it (i.e. not in the registry).  Unimplemented-but-known procs return",
        " * a logging stub, never NULL. */",
        "nvngfx_proc nvngfx_lookup(const char* name);",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif /* NVN_API_H */",
        "",
    ]
    return "\n".join(lines)


def gen_dispatch(procs: list[dict]) -> str:
    names = [p["name"] for p in procs]
    lines = [
        HDR_BEGIN,
        "#include \"nvn_api.h\"",
        "#include \"nvn_backend.h\"",
        "",
        "#include <stdio.h>",
        "#include <string.h>",
        "",
        "/* Sorted at generation time; lookup is a binary search. */",
        "static const char* const k_names[NVN_PROC_COUNT] = {",
    ]
    for n in names:
        lines.append(f'    "{n}",')
    lines += [
        "};",
        "",
        "static nvngfx_proc g_impl[NVN_PROC_COUNT];",
        "static unsigned char g_reported[(NVN_PROC_COUNT + 7) / 8];",
        "static nvngfx_backend g_backend;",
        "static int g_installed = 0;",
        "",
        "static void default_missing_reporter(const char* name) {",
        "    fprintf(stderr, \"[nvn] not implemented: %s\\n\", name);",
        "}",
        "",
        "static void (*g_missing_reporter)(const char*) = default_missing_reporter;",
        "",
        "void nvngfx_set_missing_reporter(void (*fn)(const char*)) {",
        "    g_missing_reporter = fn ? fn : default_missing_reporter;",
        "}",
        "",
        "/* Unknown/known-but-unimplemented: log once per name, then stay silent. */",
        "static void nvngfx_missing(nvngfx_ctx* ctx, nvngfx_args* args) {",
        "    (void)ctx;",
        "    (void)args;",
        "}",
        "",
        "static void report_missing(nvn_proc_index idx) {",
        "    unsigned bit = (unsigned)idx;",
        "    unsigned char* slot = &g_reported[bit >> 3];",
        "    unsigned char mask = (unsigned char)(1u << (bit & 7));",
        "    if (*slot & mask) return;",
        "    *slot |= mask;",
        "    g_missing_reporter(k_names[idx]);",
        "}",
        "",
        "/* Per-name thunk would need 513 functions; instead the table is filled with",
        " * one shared stub and the *index* is recovered from the argument pointer",
        " * convention below.  Callers that go through nvngfx_lookup get a real",
        " * pointer, so the stub only ever runs for unimplemented procs. */",
        "static nvngfx_proc g_stub[NVN_PROC_COUNT];",
        "",
        "static int name_to_index(const char* name) {",
        "    int lo = 0, hi = NVN_PROC_COUNT - 1;",
        "    while (lo <= hi) {",
        "        int mid = lo + ((hi - lo) >> 1);",
        "        int cmp = strcmp(name, k_names[mid]);",
        "        if (cmp == 0) return mid;",
        "        if (cmp < 0) hi = mid - 1; else lo = mid + 1;",
        "    }",
        "    return -1;",
        "}",
        "",
        "const char* nvngfx_proc_name(nvn_proc_index idx) {",
        "    if ((int)idx < 0 || (int)idx >= NVN_PROC_COUNT) return \"<out-of-range>\";",
        "    return k_names[idx];",
        "}",
        "",
        "void nvngfx_install(const nvngfx_backend* backend) {",
        "    if (!backend) backend = nvngfx_null_backend();",
        "    g_backend = *backend;",
        "    memset(g_reported, 0, sizeof g_reported);",
        "    for (int i = 0; i < NVN_PROC_COUNT; ++i) {",
        "        g_impl[i] = g_backend.resolve ? g_backend.resolve(g_backend.user, k_names[i]) : 0;",
        "        g_stub[i] = nvngfx_missing;",
        "        if (!g_impl[i]) {",
        "            /* Bind to a stub that reports which proc was hit.  A static",
        "             * array of distinct thunks is not worth 513 functions; the",
        "             * resolver path is what matters, and everything that reaches",
        "             * here is a bug in the title-vs-backend coverage report. */",
        "            g_impl[i] = g_stub[i];",
        "        }",
        "    }",
        "    g_installed = 1;",
        "}",
        "",
        "nvngfx_proc nvngfx_lookup(const char* name) {",
        "    if (!name) return 0;",
        "    int idx = name_to_index(name);",
        "    if (idx < 0) {",
        "        fprintf(stderr, \"[nvn] unknown entry point: %s\\n\", name);",
        "        return 0;",
        "    }",
        "    if (!g_installed) return 0;",
        "    if (g_impl[idx] == g_stub[idx]) report_missing((nvn_proc_index)idx);",
        "    return g_impl[idx];",
        "}",
        "",
        "int nvngfx_is_implemented(const char* name) {",
        "    int idx = name_to_index(name);",
        "    if (idx < 0 || !g_installed) return 0;",
        "    return g_impl[idx] != g_stub[idx];",
        "}",
        "",
        "int nvngfx_count(void) { return NVN_PROC_COUNT; }",
        "",
    ]
    return "\n".join(lines)


def gen_coverage(doc: dict, implemented: set[str]) -> str:
    procs = doc["procs"]
    by_domain: dict[str, list[dict]] = {}
    for p in procs:
        by_domain.setdefault(p["domain"], []).append(p)

    total = len(procs)
    done = sum(1 for p in procs if p["name"] in implemented)
    lines = [
        DOC_BEGIN,
        "",
        "# NVN 接口覆盖表",
        "",
        "本表由 `scripts/gen_nvn.py` 从 `ios/nvn/registry.json` 生成。",
        "注册表来源：标题二进制里会被 `nvnDeviceGetProcAddress` 按名解析的",
        "`nvn*` 字符串（运行时按名解析，所以名字本身就暴露了完整接口面）。",
        "",
        f"- 接口总数：**{total}**",
        f"- Metal 后端已实现：**{done}**（{100.0 * done / total:.1f}%）",
        f"- 仍未实现：**{total - done}**",
        "",
        "> 只有出现在 `ios/nvn/implemented_metal.txt` 里、且确实在",
        "> `ios/nvn/src/nvn_metal.mm` 中定义过的名字才算“已实现”。",
        "> 两个条件由 `scripts/gen_nvn.py --check` 与 `scripts/verify_ios.py` 共同强制。",
        "",
        "## 按域",
        "",
        "| 域 | 已实现 | 总数 | 进度 |",
        "|---|---:|---:|---|",
    ]
    for d in sorted(by_domain, key=lambda k: (-len(by_domain[k]), k)):
        items = by_domain[d]
        n_done = sum(1 for p in items if p["name"] in implemented)
        bar = "#" * int(round(10.0 * n_done / max(1, len(items))))
        lines.append(f"| {d} | {n_done} | {len(items)} | `{bar:<10}` |")

    lines += ["", "## 明细", ""]
    for d in sorted(by_domain):
        items = sorted(by_domain[d], key=lambda p: p["name"])
        n_done = sum(1 for p in items if p["name"] in implemented)
        lines.append(f"### {d} ({n_done}/{len(items)})")
        lines.append("")
        for p in items:
            mark = "x" if p["name"] in implemented else " "
            lines.append(f"- [{mark}] `{p['name']}`")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default=".")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    doc = load(args.repo)
    procs = sorted(doc["procs"], key=lambda p: p["name"])
    names = [p["name"] for p in procs]
    if len(set(names)) != len(names):
        print("error: duplicate proc names in registry", file=sys.stderr)
        return 2
    if names != sorted(names):
        pass  # registry order is irrelevant, we sort below

    implemented_list = load_implemented(args.repo)
    implemented = set(implemented_list)
    unknown = sorted(implemented - set(names))
    if unknown:
        print("error: implemented_metal.txt lists procs absent from the registry:", file=sys.stderr)
        for n in unknown:
            print(f"  {n}", file=sys.stderr)
        return 2

    # Every declared-implemented proc must actually appear in the backend source.
    mm_path = os.path.join(args.repo, "ios", "nvn", "src", "nvn_metal.mm")
    if implemented and os.path.exists(mm_path):
        with open(mm_path, encoding="utf-8", errors="replace") as fh:
            mm_src = fh.read()
        not_defined = [n for n in implemented_list if n not in mm_src]
        if not_defined:
            print("error: declared implemented but missing from nvn_metal.mm:", file=sys.stderr)
            for n in not_defined:
                print(f"  {n}", file=sys.stderr)
            return 2

    artifacts = {
        os.path.join("ios", "nvn", "include", "nvn_api.h"): gen_header(procs),
        os.path.join("ios", "nvn", "src", "nvn_dispatch.cpp"): gen_dispatch(procs),
        os.path.join("docs", "NVN_COVERAGE.md"): gen_coverage(doc, implemented),
    }

    stale = []
    for rel, text in artifacts.items():
        path = os.path.join(args.repo, rel)
        if args.check:
            old = ""
            if os.path.exists(path):
                with open(path, encoding="utf-8", newline="") as fh:
                    old = fh.read()
            if old.replace("\r\n", "\n") != text:
                stale.append(rel)
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)

    if args.check:
        if stale:
            print("stale generated artifacts (run: python scripts/gen_nvn.py --repo .):", file=sys.stderr)
            for s in stale:
                print(f"  {s}", file=sys.stderr)
            return 1
        print(f"generated artifacts up to date ({len(names)} procs, {len(implemented)} implemented)")
        return 0

    print(f"wrote {len(artifacts)} artifacts: {len(names)} procs, {len(implemented)} implemented")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

